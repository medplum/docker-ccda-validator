#!/usr/bin/env bash
# Commit what scripts/remediate-vulnerabilities.sh changed and open (or update)
# the pull requests that ship it.
#
#   scripts/open-remediation-prs.sh [OUTPUT_DIR]
#
# Two PRs at most:
#   1. medplum/reference-ccda-validator, if the pom gained pins.
#   2. medplum/docker-ccda-validator: submodule pointers, Dockerfile, and a
#      VERSION bump, with the report as the description. Merging it is what
#      triggers publish-image.yml.
#
# Both use the fixed branch auto/vuln-remediation and are force-pushed, so each
# scheduled run refreshes the same PR instead of opening another. Do not push
# hand edits to that branch; branch off it instead.
#
# Needs GH_TOKEN with contents and pull-requests write on both repositories
# (the default GITHUB_TOKEN cannot push to the fork).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$(cd "${1:-$ROOT/remediation}" && pwd)"
BRANCH="${REMEDIATION_BRANCH:-auto/vuln-remediation}"
DOCKER_REPO="${DOCKER_REPO:-medplum/docker-ccda-validator}"
DOCKER_BASE="${DOCKER_BASE:-main}"
VALIDATOR_REPO="${VALIDATOR_REPO:-medplum/reference-ccda-validator}"
VALIDATOR_BASE="${VALIDATOR_BASE:-master}"
VALIDATOR="$ROOT/submodules/reference-ccda-validator"
: "${GH_TOKEN:?GH_TOKEN is required}"

summary="$OUT/summary.json"
verified="$(jq -r '.verified' "$summary")"
draft=()
[[ "$verified" == true ]] || draft=(--draft)

push() {  # push DIR REPO
  # Clear any credential header actions/checkout left behind, so the bot
  # token below is the one that authenticates.
  git -C "$1" -c http.https://github.com/.extraheader= \
    push --force "https://x-access-token:${GH_TOKEN}@github.com/$2.git" "HEAD:refs/heads/$BRANCH"
}

upsert_pr() {  # upsert_pr REPO BASE TITLE BODY_FILE -> prints PR URL
  local repo="$1" base="$2" title="$3" body="$4" number
  number="$(gh pr list -R "$repo" --head "$BRANCH" --state open --json number -q '.[0].number')"
  if [[ -n "$number" ]]; then
    gh pr edit "$number" -R "$repo" --title "$title" --body-file "$body" >/dev/null
    # Keep draft state in step with this run's verification, not the first run's.
    if [[ "$verified" == true ]]; then
      gh pr ready "$number" -R "$repo" >/dev/null 2>&1 || true
    else
      gh pr ready --undo "$number" -R "$repo" >/dev/null 2>&1 || true
    fi
    gh pr view "$number" -R "$repo" --json url -q .url
  else
    gh pr create -R "$repo" --base "$base" --head "$BRANCH" --title "$title" --body-file "$body" "${draft[@]}"
  fi
}

pin_lines() {
  jq -r '.changes[] | "- \(.artifact) \(.from) -> \(.to) via \(.how) (\(.ids | join(", ")))"' "$OUT/pins.json"
}

# --- 1. The validator fork ----------------------------------------------------
validator_pr=""
if ! git -C "$VALIDATOR" diff --quiet -- pom.xml; then
  artifacts="$(jq -r '[.changes[].artifact | split(":")[1]] | unique | join(", ")' "$OUT/pins.json")"
  advisories="$(jq -r '[.changes[].ids[]] | unique | length' "$OUT/pins.json")"
  title="fix(deps): bump ${artifacts} to clear ${advisories} advisories"
  git -C "$VALIDATOR" checkout -B "$BRANCH"
  git -C "$VALIDATOR" commit -q -s -m "$title" -m "$(pin_lines)" \
    -m "Generated by docker-ccda-validator's remediate-vulnerabilities workflow. Pins go in this pom because its dependencyManagement governs every jar in the WAR, including the forks' transitives."
  push "$VALIDATOR" "$VALIDATOR_REPO"
  {
    echo "Automated vulnerability remediation for the jars in \`referenceccdaservice.war\`."
    echo
    pin_lines
    echo
    if [[ "$verified" == true ]]; then
      echo "Verification passed: WAR build, \`mvn verify\`, \`--no-cache\` image build, and a container smoke test that validates a sample C-CDA."
    else
      echo "**A verification step failed** — see the report in the docker-ccda-validator PR."
    fi
    echo
    echo "**Merge with a merge commit, not a squash.** The docker-ccda-validator PR pins this branch's commit as its submodule, and a squash would leave that commit unreachable once the branch is deleted."
    echo
    echo "🤖 Generated with [Claude Code](https://claude.com/claude-code)"
  } > "$OUT/validator-pr.md"
  validator_pr="$(upsert_pr "$VALIDATOR_REPO" "$VALIDATOR_BASE" "$title" "$OUT/validator-pr.md")"
  echo "validator PR: $validator_pr"
fi

# --- 2. This repo -------------------------------------------------------------
cd "$ROOT"
git fetch -q origin "$DOCKER_BASE"
base_version="$(git show "origin/$DOCKER_BASE:VERSION")"
IFS=. read -r maj min pat <<< "$base_version"
version="$maj.$min.$((pat + 1))"
echo "$version" > VERSION

reasons="$(jq -r '.release_reasons | join("; ")' "$summary")"
title="chore: remediate vulnerabilities, bump VERSION to $version"
git checkout -q -B "$BRANCH"
git add VERSION Dockerfile submodules/
git commit -q -s -m "$title" -m "Reasons: $reasons" -m "$(pin_lines)"
push "$ROOT" "$DOCKER_REPO"

{
  if [[ -n "$validator_pr" ]]; then
    echo "> **Merge $validator_pr first** (merge commit), then this. The submodule here points at that PR's commit."
    echo
  fi
  if [[ "$verified" != true ]]; then
    echo "> **Draft:** a verification step failed. Check the table below and the workflow run before merging."
    echo
  fi
  echo "Why this run produced a release: $reasons."
  echo
  echo "Merging bumps \`VERSION\` to \`$version\`, which runs \`publish-image.yml\`: a \`--pull --no-cache\` build pushed to ECR with the media type Inspector needs. Deploying the new tag is still a separate step."
  echo
  if [[ -n "${GITHUB_RUN_ID:-}" ]]; then
    echo "Workflow run: ${GITHUB_SERVER_URL}/${GITHUB_REPOSITORY}/actions/runs/${GITHUB_RUN_ID}"
    echo
  fi
  # GitHub rejects bodies over 65536 characters; the full report is in the run artifacts.
  head -c 60000 "$OUT/report.md"
  echo
  echo
  echo "🤖 Generated with [Claude Code](https://claude.com/claude-code)"
} > "$OUT/docker-pr.md"
upsert_pr "$DOCKER_REPO" "$DOCKER_BASE" "$title" "$OUT/docker-pr.md"
